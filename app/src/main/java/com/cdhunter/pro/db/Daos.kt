    suspend fun upsertAll(results: List<SniResultEntity>)

    @Query("SELECT * FROM sni_results ORDER BY testedAtMs DESC")
    fun observeAll(): Flow<List<SniResultEntity>>

    @Query("SELECT * FROM sni_results WHERE ip = :ip")
    suspend fun forIp(ip: String): List<SniResultEntity>

    @Query("SELECT * FROM sni_results WHERE ok = 1 AND certMatched = 1 AND providerId = :providerId ORDER BY testedAtMs DESC")
    suspend fun verifiedFor(providerId: String): List<SniResultEntity>

    @Query("SELECT sni, COUNT(*) AS c FROM sni_results WHERE ok = 1 AND certMatched = 1 GROUP BY sni ORDER BY c DESC LIMIT 1")
    suspend fun bestSniOverall(): BestSniRow?

    @Query("DELETE FROM sni_results WHERE expiresAtMs < :nowMs")
    suspend fun deleteExpired(nowMs: Long)

    @Query("DELETE FROM sni_results")
    suspend fun clear()
}

data class BestSniRow(val sni: String, val c: Int)

