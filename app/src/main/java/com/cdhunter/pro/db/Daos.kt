@Dao
interface ScanDao {
    @Insert
    suspend fun insert(scan: ScanEntity): Long

    @Query("SELECT * FROM scans WHERE id = :id")
    suspend fun getById(id: Long): ScanEntity?

    @Query("SELECT * FROM scans ORDER BY startedAtMs DESC LIMIT 100")
    fun observeRecent(): Flow<List<ScanEntity>>

    @Query("SELECT * FROM scans ORDER BY startedAtMs DESC LIMIT 100")
    suspend fun recentOnce(): List<ScanEntity>

    @Query("SELECT * FROM scans WHERE status IN ('RUNNING','PAUSED') ORDER BY id DESC LIMIT 1")
    suspend fun activeScan(): ScanEntity?

    @Query("UPDATE scans SET status = :status, finishedAtMs = :finishedAtMs, pauseReason = :pauseReason WHERE id = :id")
    suspend fun finish(id: Long, status: String, finishedAtMs: Long?, pauseReason: String?)

    @Query("UPDATE scans SET status = :status WHERE id = :id")
    suspend fun setStatus(id: Long, status: String)

    @Query(
        "UPDATE scans SET testedCount = :tested, reachableCount = :reachable, verifiedCount = :verified, " +
            "errorCount = :errors, bytesUsed = :bytes, cursorIndex = :cursor, heartbeatAtMs = :heartbeat " +
            "WHERE id = :id",
    )
    suspend fun updateProgress(
        id: Long, tested: Int, reachable: Int, verified: Int, errors: Int,
        bytes: Long, cursor: Int, heartbeat: Long,
    )

    @Query("DELETE FROM scans WHERE id = :id")
    suspend fun delete(id: Long)
}

@Dao
interface ResultDao {
    // REPLACE (not @Upsert) because rows are keyed by the UNIQUE (scanId, ip, port)
    // index while the autoGenerated id is never set by callers.
    @Insert(onConflict = OnConflictStrategy.REPLACE)
    suspend fun upsertAll(results: List<ResultEntity>)

    @Insert(onConflict = OnConflictStrategy.REPLACE)
    suspend fun upsert(result: ResultEntity)

    @Query("SELECT * FROM results WHERE scanId = :scanId")
    fun observeForScan(scanId: Long): Flow<List<ResultEntity>>

    @Query("SELECT * FROM results WHERE scanId = :scanId")
    suspend fun forScanOnce(scanId: Long): List<ResultEntity>

    @Query("SELECT * FROM results WHERE ip = :ip ORDER BY testedAtMs DESC")
    suspend fun forIp(ip: String): List<ResultEntity>

    @Query("SELECT * FROM results WHERE score IS NOT NULL ORDER BY score DESC LIMIT 1")
    suspend fun bestEver(): ResultEntity?

    @Query("SELECT MAX(testedAtMs) FROM results WHERE tcpOk = 1")
    suspend fun lastSuccessAt(): Long?

    @Query("SELECT COUNT(*) FROM results")
    suspend fun countAll(): Int

    @Query("SELECT COUNT(*) FROM results WHERE scanId = :scanId AND tcpOk = 1")
    suspend fun countReachable(scanId: Long): Int

    @Query("SELECT COUNT(*) FROM results WHERE scanId = :scanId AND verdict = 'VERIFIED_COMPATIBLE'")
    suspend fun countVerified(scanId: Long): Int

    @Query("SELECT COUNT(*) FROM results WHERE scanId = :scanId AND errorCategory IS NOT NULL AND errorCategory != 'NONE'")
    suspend fun countErrors(scanId: Long): Int

    @Query("DELETE FROM results WHERE scanId = :scanId")
    suspend fun deleteForScan(scanId: Long)
}

@Dao
