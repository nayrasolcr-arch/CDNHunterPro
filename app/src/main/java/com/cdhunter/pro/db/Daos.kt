/** Transaction helpers used by repositories. */
@Dao
abstract class ScanTxDao {
    @Transaction
    open suspend fun deleteScanWithResults(scanId: Long, scanDao: ScanDao, resultDao: ResultDao) {
        resultDao.deleteForScan(scanId)
        scanDao.delete(scanId)
    }
}
